"""Paper-trading bots: registry -> generated configs + compose file, and a tiny status client.

user_data/configs/bots.json lists the bots (name, strategy, FreqUI port, why it runs).
`lab.py bots generate` turns it into:
  - user_data/configs/dryrun/<name>.json   per-bot overrides on top of base.json
  - docker-compose.bots.yml                one dry-run container per bot
Both are generated - edit bots.json, never the outputs.

Every bot:
  - runs `freqtrade trade --dry-run` (Freqtrade itself strips exchange secrets),
  - depends on the `safety` service in docker-compose.yml,
  - has its own SQLite database and log file, and its own FreqUI port on 127.0.0.1 only,
  - reads the FreqUI login from .env (FREQTRADE__API_SERVER__*), never from a committed file.
Standard library only.
"""

from __future__ import annotations

import base64
import json
import re
import urllib.error
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REGISTRY = ROOT / "user_data" / "configs" / "bots.json"
DRYRUN_DIR = ROOT / "user_data" / "configs" / "dryrun"
COMPOSE_BOTS = ROOT / "docker-compose.bots.yml"
NAME = re.compile(r"^[a-z0-9][a-z0-9-]{1,30}$")
STATUSES = ("promoted", "watch-list", "baseline")


# --------------------------------------------------------------------------- registry

def load_registry(path: Path = REGISTRY) -> list[dict]:
    bots = json.loads(path.read_text())["bots"]
    names, ports = set(), set()
    for b in bots:
        for key in ("name", "strategy", "port", "status", "reason"):
            if key not in b:
                raise SystemExit(f"bots.json: bot {b.get('name', '?')} is missing '{key}'")
        if not NAME.match(b["name"]):
            raise SystemExit(f"bots.json: bad name '{b['name']}' (lowercase letters, digits, dashes)")
        if b["status"] not in STATUSES:
            raise SystemExit(f"bots.json: status of {b['name']} must be one of {STATUSES}")
        if not 1024 <= int(b["port"]) <= 65535:
            raise SystemExit(f"bots.json: port of {b['name']} must be 1024-65535")
        if b["name"] in names or b["port"] in ports:
            raise SystemExit(f"bots.json: duplicate name or port for {b['name']}")
        names.add(b["name"])
        ports.add(b["port"])
    return bots


def pinned_image(compose: Path = ROOT / "docker-compose.yml") -> str:
    """The exact image (tag + digest) docker-compose.yml pins, so bots and backtests match."""
    m = re.search(r"^x-freqtrade-image:\s*&\S+\s+(\S+)", compose.read_text(), re.MULTILINE)
    if not m:
        raise SystemExit("could not find x-freqtrade-image in docker-compose.yml")
    return m.group(1)


# --------------------------------------------------------------------------- generated files

def dryrun_config(bot: dict, all_bots: list[dict]) -> dict:
    # Any bot's FreqUI may add the others ("multi-bot" view), so all of them are allowed origins.
    origins = sorted({f"http://{host}:{b['port']}" for b in all_bots for host in ("127.0.0.1", "localhost")})
    return {
        "bot_name": f"lab-{bot['name']}",
        "strategy": bot["strategy"],
        "dry_run": True,
        "dry_run_wallet": 1000,
        "initial_state": "running",
        "api_server": {
            "enabled": True,
            "listen_ip_address": "0.0.0.0",  # inside the container; the host side is bound to 127.0.0.1
            "listen_port": 8080,
            "verbosity": "error",
            "enable_openapi": False,
            "CORS_origins": origins,
        },
    }


def compose_text(bots: list[dict], image: str) -> str:
    lines = [
        "# GENERATED by `python3 scripts/lab.py bots generate` from user_data/configs/bots.json - do not edit.",
        "# Use with docker-compose.yml (it defines the `safety` service every bot waits for):",
        "#   python3 scripts/lab.py bots up | down | status | logs",
        "services:",
    ]
    for b in bots:
        name = b["name"]
        command = json.dumps([
            "trade", "--dry-run",
            "--config", "user_data/configs/base.json",
            "--config", f"user_data/configs/dryrun/{name}.json",
            "--db-url", f"sqlite:////freqtrade/user_data/db/{name}.sqlite",
            "--logfile", f"user_data/logs/{name}.log",
        ])
        lines += [
            f"  bot-{name}:",
            f"    # {b['status']}: {b['strategy']} - {b['reason']}",
            f"    image: {image}",
            f"    container_name: crypto-lab-bot-{name}",
            "    restart: unless-stopped",
            "    depends_on:",
            "      safety:",
            "        condition: service_completed_successfully",
            "    env_file:",
            "      - path: .env",
            "        required: true",
            f"      - path: .env.bot-{name}",
            "        required: false",
            "    environment:",
            "      PYTHONPATH: /freqtrade/user_data/strategies",
            "    volumes:",
            "      - ./user_data:/freqtrade/user_data",
            "    ports:",
            f"      - \"127.0.0.1:{b['port']}:8080\"",
            f"    command: {command}",
        ]
    return "\n".join(lines) + "\n"


def write_all(bots: list[dict] | None = None) -> list[Path]:
    bots = load_registry() if bots is None else bots
    DRYRUN_DIR.mkdir(parents=True, exist_ok=True)
    written = []
    wanted = {f"{b['name']}.json" for b in bots}
    for stale in DRYRUN_DIR.glob("*.json"):
        if stale.name not in wanted:
            stale.unlink()
    for b in bots:
        path = DRYRUN_DIR / f"{b['name']}.json"
        path.write_text(json.dumps(dryrun_config(b, bots), indent=2) + "\n")
        written.append(path)
    COMPOSE_BOTS.write_text(compose_text(bots, pinned_image()))
    written.append(COMPOSE_BOTS)
    return written


# --------------------------------------------------------------------------- status client

def api_get(port: int, path: str, user: str | None = None, password: str | None = None, timeout: float = 5.0):
    req = urllib.request.Request(f"http://127.0.0.1:{port}/api/v1/{path}")
    if user is not None:
        token = base64.b64encode(f"{user}:{password}".encode()).decode()
        req.add_header("Authorization", f"Basic {token}")
    with urllib.request.urlopen(req, timeout=timeout) as resp:
        return json.loads(resp.read())


def bot_status(bot: dict, user: str, password: str) -> dict:
    out = {"name": bot["name"], "strategy": bot["strategy"], "port": bot["port"], "status": bot["status"]}
    try:
        api_get(bot["port"], "ping")
    except (urllib.error.URLError, OSError, ValueError) as exc:
        return {**out, "reachable": False, "error": str(getattr(exc, "reason", exc))}
    out["reachable"] = True
    try:
        cfg = api_get(bot["port"], "show_config", user, password)
        profit = api_get(bot["port"], "profit", user, password)
        open_trades = api_get(bot["port"], "status", user, password)
    except urllib.error.HTTPError as exc:
        return {**out, "error": f"API {exc.code} (wrong FreqUI login in .env?)"}
    out.update(
        dry_run=cfg.get("dry_run"),
        state=cfg.get("state"),
        running_strategy=cfg.get("strategy"),
        open_trades=len(open_trades),
        closed_trades=profit.get("closed_trade_count", 0),
        profit_closed_pct=profit.get("profit_closed_percent", 0.0),
        profit_all_pct=profit.get("profit_all_percent", 0.0),
        first_trade=profit.get("first_trade_date") or "-",
    )
    return out
