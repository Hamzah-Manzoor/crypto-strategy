"""Robustness check helpers (standard library only): build the variant strategies and the report.

Plan and rules: docs/research/robustness-check-plan.md, numbers in rules.ROBUSTNESS.
lab.py robustness <Strategy> uses these to:
  R1 timing    - weekly strategies: every rebalance slot `timing_step_hours` apart (28 slots);
                 daily strategies: every decision hour `timing_step_hours` apart (4 slots), plus
                 acting on the daily view 1, 2, 3 days late (if the strategy has DELAY_DAYS);
                 signal strategies: act on entry/exit signals 1, 2, 3 candles late
  R2 settings  - each declared setting moved to each neighbour value, one at a time
  R3 coins     - leave one coin out (5 runs)
  R4 trades    - profit without the best N trades (from the original's trades; no re-run)
Variant classes subclass the original and are written to a throwaway folder that
Freqtrade loads with --strategy-path.
"""

from __future__ import annotations

from pprint import pformat

import rules


def timing_slots(original: tuple[int, int], step_hours: int) -> list[tuple[int, int]]:
    """All (weekday, hour) slots `step_hours` apart, aligned so the original slot is included."""
    weekday0, hour0 = original
    hours = sorted({(hour0 + i * step_hours) % 24 for i in range(24 // step_hours)})
    return [(day, hour) for day in range(7) for hour in hours]


def _class(parent: str, module: str, name: str, doc: str, body: list[str]) -> str:
    lines = "\n".join(f"    {line}" if line else "" for line in body) or "    pass"
    return f'''"""{doc} GENERATED by lab.py robustness - throwaway, never committed."""

from {module} import {parent}


class {name}({parent}):
{lines}
'''


def timing_variants(info: dict) -> dict[str, str]:
    name, module = info["strategy"], info["module"]
    out = {}
    if info["weekly"]:
        for day, hour in timing_slots(tuple(info["rebalance"]), rules.ROBUSTNESS["timing_step_hours"]):
            cls = f"{name}_R1_d{day}h{hour:02d}"
            out[cls] = _class(name, module, cls, f"R1 timing: rebalance on weekday {day} at {hour:02d}:00 UTC.",
                              [f"REBALANCE_WEEKDAY, REBALANCE_HOUR = {day}, {hour}"])
    elif info.get("daily"):
        step, hour0 = rules.ROBUSTNESS["timing_step_hours"], info["rebalance"][0]
        for hour in sorted({(hour0 + i * step) % 24 for i in range(24 // step)}):
            cls = f"{name}_R1_h{hour:02d}"
            out[cls] = _class(name, module, cls, f"R1 timing: decide on the {hour:02d}:00 UTC candle.",
                              [f"REBALANCE_HOUR = {hour}"])
        if info.get("delay_days"):
            for k in rules.ROBUSTNESS["signal_delays"]:
                cls = f"{name}_R1_delay{k}"
                out[cls] = _class(name, module, cls, f"R1 timing: act on the daily view from {k} day(s) ago.",
                                  [f"DELAY_DAYS = {k}"])
    else:
        for k in rules.ROBUSTNESS["signal_delays"]:
            cls = f"{name}_R1_late{k}"
            body = []
            for method, cols in (("populate_entry_trend", ("enter_long", "enter_tag")),
                                 ("populate_exit_trend", ("exit_long", "exit_tag"))):
                body += [
                    f"def {method}(self, dataframe, metadata):",
                    f"    dataframe = super().{method}(dataframe, metadata)",
                    f"    # act on the strategy's own signal {k} candle(s) later: past data only, no lookahead",
                    f"    if '{cols[0]}' in dataframe:",
                    f"        dataframe['{cols[0]}'] = dataframe['{cols[0]}'].shift({k}).fillna(0)",
                    f"    if '{cols[1]}' in dataframe:",
                    f"        dataframe['{cols[1]}'] = dataframe['{cols[1]}'].shift({k})",
                    "    return dataframe",
                    "",
                ]
            out[cls] = _class(name, module, cls, f"R1 timing: signals acted on {k} candle(s) late.", body)
    return out


def setting_variants(info: dict) -> dict[str, str]:
    name, module = info["strategy"], info["module"]
    out = {}
    for key, spec in info["settings"].items():
        for value in spec["values"]:
            if value == spec["default"]:
                continue
            cls = f"{name}_R2_{key}_{str(value).replace('.', 'p').replace('-', 'm')}"
            line = (f"{spec['space']}_params = {pformat({key: value})}" if spec["kind"] == "param"
                    else f"{key} = {value!r}")
            out[cls] = _class(name, module, cls, f"R2 settings: {key} = {value!r} (default {spec['default']!r}).", [line])
    return out


def coin_variants(info: dict, pairs: list[str]) -> list[dict]:
    """One run per left-out coin: {"left_out", "pairs", "class", "source"} (class None = original)."""
    name, module = info["strategy"], info["module"]
    out = []
    for coin in pairs:
        rest = [p for p in pairs if p != coin]
        run = {"left_out": coin, "pairs": rest, "class": None, "source": None}
        if info["universe"]:  # the strategy ranks its own coin list: drop the coin there too
            cls = f"{name}_R3_no{coin.split('/')[0]}"
            universe = tuple(p for p in info["universe"] if p != coin)
            body = [
                f"UNIVERSE = {universe!r}",
                "",
                "def populate_indicators(self, dataframe, metadata):",
                "    # The left-out coin is not traded at all (it can still appear in a bias check's pair list).",
                "    if metadata['pair'] not in self.UNIVERSE:",
                "        dataframe['mom_ret_1d'] = float('nan')",
                "        dataframe['mom_rank_1d'] = float('nan')",
                "        dataframe['btc_ok_1d'] = 0.0",
                "        return dataframe",
                "    return super().populate_indicators(dataframe, metadata)",
            ]
            run.update({"class": cls, "source": _class(name, module, cls, f"R3 coins: without {coin}.", body)})
        out.append(run)
    return out


def render_report(record: dict) -> str:
    o = record["original"]
    lines = [
        f"# Robustness · {record['strategy']}", "",
        f"Run `{record['id']}` · dev period `{record['timerange']}` · 1h · fee 0.10% per side · "
        f"original: {o['profit_pct']:+.1f}%, max DD {o['max_dd_pct']:.1f}%, Calmar {o['calmar']:.2f}, {o['trades']} trades", "",
        f"## Verdict: **{record['overall']}**", "",
        "| Check | Verdict | Detail |", "|---|---|---|",
        *[f"| {c} | **{v['verdict']}** | {v['detail']} |" for c, v in record["checks"].items()],
        "",
        ("No generated variants to bias-check." if not record["bias"]["checked"] else
         f"Bias check on all {record['bias']['checked']} generated variants: "
         + ("all passed" if not record["bias"]["failed"] else f"FAILED: {', '.join(record['bias']['failed'])}")),
        "",
    ]
    for check, label in (("R1", "R1 timing"), ("R2", "R2 neighbouring settings"), ("R3", "R3 leave one coin out")):
        rows = record["variants"].get(check, [])
        if not rows:
            continue
        lines += [f"## {label}", "", "| Variant | Profit % | Max DD % | Calmar | Trades |", "|---|---:|---:|---:|---:|"]
        lines += [f"| {r['label']} | {r['profit_pct']:+.1f} | {r['max_dd_pct']:.1f} | {r['calmar']:.2f} | {r['trades']} |"
                  for r in rows]
        lines.append("")
    lines.append("Rules: docs/TESTING_METHODOLOGY.md section 11 (numbers in scripts/rules.py → ROBUSTNESS).")
    return "\n".join(lines) + "\n"
