"""Helpers for hyperopt and walk-forward (standard library only).

- best_epoch():        read Freqtrade's .fthypt result file (one JSON line per epoch)
- render_tuned():      source of a generated "tuned" subclass, e.g. MacdVolumeV1T(MacdVolumeV1),
                       with the hyperopt settings written into the code (never a hidden param file)
- walkforward_windows(): rolling train/test date windows
- walkforward_summary(): stitch the test windows into one verdict
"""

from __future__ import annotations

import json
import math
import re
from datetime import date
from pathlib import Path
from pprint import pformat

STRATEGIES = Path(__file__).resolve().parent.parent / "user_data" / "strategies"


# --------------------------------------------------------------------------- hyperopt results

def best_epoch(fthypt: Path) -> dict:
    """The best (lowest loss) epoch of a hyperopt run, plus how many epochs ran."""
    epochs = [json.loads(line) for line in Path(fthypt).read_text().splitlines() if line.strip()]
    if not epochs:
        raise SystemExit(f"{fthypt} has no epochs")
    best = min(epochs, key=lambda e: e["loss"])
    m = best["results_metrics"]
    return {
        "epoch": best["current_epoch"],
        "epochs_run": len(epochs),
        # Freqtrade skips epochs whose settings repeat an earlier one, so the count can be
        # lower than requested; the last epoch number shows whether the run finished.
        "last_epoch": max(e["current_epoch"] for e in epochs),
        "loss": best["loss"],
        "params": best["params_details"],
        # Freqtrade's own numbers for the best epoch (closed trades only).
        "metrics": {
            "trades": m.get("total_trades"),
            "profit_pct": 100 * m.get("profit_total", 0.0),
            "max_dd_pct": 100 * m.get("max_drawdown_account", 0.0),
            "sharpe": m.get("sharpe"),
            "calmar": m.get("calmar"),
            "win_rate_pct": 100 * m.get("winrate", 0.0),
            "profit_factor": m.get("profit_factor"),
            "days": m.get("backtest_days"),
        },
    }


# --------------------------------------------------------------------------- tuned subclasses

def find_strategy_file(class_name: str, folder: Path = STRATEGIES) -> Path:
    for f in sorted(folder.glob("*.py")):
        if re.search(rf"^class {class_name}\(", f.read_text(), re.MULTILINE):
            return f
    raise SystemExit(f"strategy class {class_name} not found in {folder}")


def tuned_names(parent: str, parent_file: Path, suffix: str = "T") -> tuple[str, str]:
    """(class name, file name) of the tuned version: MacdVolumeV1 -> MacdVolumeV1T, macd_volume_v1t.py."""
    return f"{parent}{suffix}", f"{parent_file.stem}{suffix.lower()}.py"


def render_tuned(parent: str, parent_module: str, name: str, params: dict, meta: dict) -> str:
    """Python source for a subclass that only pins the tuned settings."""
    body = []
    for space in ("buy", "sell"):
        if params.get(space):
            body.append(f"    {space}_params = {pformat(params[space], indent=4, sort_dicts=True)}")
    if "stoploss" in params:
        body.append(f"    stoploss = {params['stoploss']['stoploss']!r}")
    for key, value in (params.get("trailing") or {}).items():
        body.append(f"    {key} = {value!r}")
    lines = "\n".join(body) or "    pass"
    header = "\n".join(f"{k}: {v}" for k, v in meta.items())
    return f'''"""
{name}: {parent} with settings tuned by hyperopt.
GENERATED by `python3 scripts/lab.py hyperopt` - do not edit by hand. To re-tune, run
hyperopt again (it refuses to overwrite this file without --force, because this
version may already have logged results).

Same trading idea and code as {parent}; only the settings below differ.

{header}
"""

from {parent_module} import {parent}


class {name}({parent}):
{lines}
'''


# --------------------------------------------------------------------------- walk-forward

def parse_ymd(s: str) -> date:
    return date(int(s[:4]), int(s[4:6]), int(s[6:8]))


def ymd(d: date) -> str:
    return d.strftime("%Y%m%d")


def add_months(d: date, months: int) -> date:
    y, m = divmod(d.month - 1 + months, 12)
    return date(d.year + y, m + 1, d.day)


def walkforward_windows(start: str, end: str, train_months: int = 12, test_months: int = 3,
                        step_months: int = 3) -> list[dict]:
    """Rolling windows: tune on `train_months`, test on the following `test_months`,
    slide by `step_months`. Test windows never overlap and never pass `end`."""
    windows, k = [], 0
    s, stop = parse_ymd(start), parse_ymd(end)
    while True:
        train_start = add_months(s, k * step_months)
        train_end = add_months(train_start, train_months)
        test_end = add_months(train_end, test_months)
        if test_end > stop:
            break
        windows.append({"k": k, "train": f"{ymd(train_start)}-{ymd(train_end)}",
                        "test": f"{ymd(train_end)}-{ymd(test_end)}"})
        k += 1
    return windows


def annualise(profit_pct: float, days: float) -> float:
    if days <= 0 or profit_pct <= -100:
        return -100.0
    return 100 * ((1 + profit_pct / 100) ** (365 / days) - 1)


def walkforward_summary(rows: list[dict]) -> dict:
    """rows: one per window with train_profit_pct, train_days, test_profit_pct, test_days,
    test_max_dd_pct, test_trades, bh_test_profit_pct.

    Walk-forward efficiency = yearly return on the stitched test windows / average yearly
    return of the training runs. ~1: tuning carried forward. ~0 or below: it fit noise."""
    growth = math.prod(1 + r["test_profit_pct"] / 100 for r in rows)
    bh_growth = math.prod(1 + r["bh_test_profit_pct"] / 100 for r in rows)
    test_days = sum(r["test_days"] for r in rows)
    stitched = 100 * (growth - 1)
    test_cagr = annualise(stitched, test_days)
    train_yearly = [annualise(r["train_profit_pct"], r["train_days"]) for r in rows]
    mean_train = sum(train_yearly) / len(train_yearly)
    return {
        "windows": len(rows),
        "profitable_windows_pct": 100 * sum(r["test_profit_pct"] > 0 for r in rows) / len(rows),
        "stitched_profit_pct": stitched,
        "stitched_cagr_pct": test_cagr,
        "bh_stitched_profit_pct": 100 * (bh_growth - 1),
        "mean_train_yearly_pct": mean_train,
        "wf_efficiency": test_cagr / mean_train if mean_train > 0 else None,
        "worst_window_dd_pct": max(r["test_max_dd_pct"] for r in rows),
        "total_test_trades": sum(r["test_trades"] for r in rows),
    }
